#[derive(Serialize)]
pub struct Address {
    pub address: String,
    pub interface: String,
}

#[derive(Serialize)]
pub struct NetworkInfo {
    pub hostname: String,
    pub addresses: Vec<Address>,
}

pub fn info() -> Result<NetworkInfo, String> {
    let mut addresses: Vec<_> = if_addrs::get_if_addrs()
        .map_err(|e| e.to_string())?
        .into_iter()
        .filter(|i| {
            i.is_oper_up()
                && !i.is_p2p
                && match i.ip() {
                    IpAddr::V4(ip) => {
                        !ip.is_loopback() && !ip.is_unspecified() && !ip.is_link_local()
                    }
                    IpAddr::V6(ip) => {
                        !ip.is_loopback()
                            && !ip.is_unspecified()
                            && ip.segments()[0] & 0xffc0 != 0xfe80
                    }
                }
        })
        .map(|i| Address {
            address: i.ip().to_string(),
            interface: i.name,
        })
        .collect();
    addresses.sort_by_key(|i| {
        (
            i.address.contains(':'),
            i.interface != "en0",
            i.interface.clone(),
            i.address.clone(),
        )
    });
    addresses.dedup_by(|a, b| a.address == b.address);
    Ok(NetworkInfo {
        hostname: hostname::get()
            .map_err(|e| e.to_string())?
            .to_string_lossy()
            .into_owned(),
        addresses,
    })
}

/// Explains a server address that no longer belongs to this computer (DHCP handed it a new
/// one, or it moved networks) and names the addresses it has now.
pub fn missing_address(address: IpAddr) -> String {
    let current: Vec<_> = info()
        .map(|i| i.addresses)
        .unwrap_or_default()
        .into_iter()
        .filter(|a| {
            a.address
                .parse::<IpAddr>()
                .is_ok_and(|ip| ip.is_ipv4() == address.is_ipv4())
        })
        .map(|a| format!("{} ({})", a.address, a.interface))
        .collect();
    if current.is_empty() {
        format!("{address} is not an address of this computer, and it has no other network address right now. Check its network connection, or choose another address in Settings > Network access.")
    } else {
        format!(
            "{address} is no longer an address of this computer. It now has {}. Choose the new address in Settings > Network access.",
            current.join(", ")
        )
    }
}

/// Whether a certificate this app generated lists the name clients use for the server.
pub fn covers(record: &GeneratedCertificate, server_name: &str) -> bool {
    let Ok(host) = host_name(server_name) else {
        return false;
    };
    record.names.iter().any(
        |name| match (name.parse::<IpAddr>(), host.parse::<IpAddr>()) {
            (Ok(a), Ok(b)) => a == b,
            (Err(_), Err(_)) => name.eq_ignore_ascii_case(&host),
            _ => false,
        },
    )
}

#[derive(Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GeneratedCertificate {
    pub certificate: String,
    pub private_key: String,
    pub trust_certificate: String,
    pub fingerprint: String,
    pub expires: String,
    pub names: Vec<String>,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct WorkspaceTrust {
    pub certificate: GeneratedCertificate,
    pub server_name: String,
    pub platform: &'static str,
}

// Import only the CA created for the selected local server. Compare the bytes with
// the fingerprint shown in the confirmation; metadata alone must never authorize trust.
pub fn verified_generated(
    directory: &Path,
    certificate: &str,
) -> Result<GeneratedCertificate, String> {
    let record = generated(directory, certificate).ok_or("This certificate was not generated by Hardcharger. Trust your certificate authority using the operating system's certificate manager.")?;
    let file = Path::new(&record.trust_certificate);
    let folder = file
        .parent()
        .ok_or("Missing certificate folder.")?
        .canonicalize()
        .map_err(|e| e.to_string())?;
    let actual = file.canonicalize().map_err(|e| e.to_string())?;
    if actual.parent() != Some(folder.as_path()) {
        return Err("The trust certificate points outside its generated folder.".into());
    }
    let certificates = pem::parse_many(fs::read(&actual).map_err(|e| e.to_string())?)
        .map_err(|e| e.to_string())?;
    if certificates.len() != 1 || certificates[0].tag() != "CERTIFICATE" {
        return Err("The generated CA file must contain exactly one certificate.".into());
    }
    let chain = pem::parse_many(fs::read(certificate).map_err(|e| e.to_string())?)
        .map_err(|e| e.to_string())?;
    if chain.len() != 2 || chain[1].contents() != certificates[0].contents() {
        return Err("The trust certificate no longer matches this server's certificate chain. Generate a new certificate.".into());
    }
    let fingerprint = Sha256::digest(certificates[0].contents())
        .iter()
        .map(|b| format!("{b:02X}"))
        .collect::<Vec<_>>()
        .join(":");
    if fingerprint != record.fingerprint {
        return Err(
            "The CA certificate changed. Generate a new certificate before trusting it.".into(),
        );
    }
    Ok(record)
}

pub fn workspace_trust(directory: &Path, settings: &Settings) -> Result<WorkspaceTrust, String> {
    if !settings.network.enabled || !settings.network.tls {
        return Err("This server is not using network TLS.".into());
    }
    Ok(WorkspaceTrust {
        certificate: verified_generated(directory, &settings.network.tls_cert)?,
        server_name: host_name(&settings.network.server_name)?,
        platform: std::env::consts::OS,
    })
}

#[cfg(any(target_os = "macos", test))]
fn macos_trust_args(server_name: &str, certificate: &Path) -> Vec<std::ffi::OsString> {
    // Default user trust domain; SSL and this hostname only. Never the admin/system
    // domain, never hostname/expiry exceptions, and never a shell command string.
    [
        "add-trusted-cert",
        "-r",
        "trustRoot",
        "-p",
        "ssl",
        "-s",
        server_name,
    ]
    .iter()
    .map(|value| std::ffi::OsString::from(*value))
    .chain(std::iter::once(certificate.as_os_str().into()))
    .collect()
}

pub fn trust_workspace_ca(
    directory: &Path,
    settings: &Settings,
    fingerprint: &str,
    server_name: &str,
) -> Result<(), String> {
    let trust = workspace_trust(directory, settings)?;
    if trust.certificate.fingerprint != fingerprint || trust.server_name != server_name {
        return Err("The server or certificate changed while the trust prompt was open. Open the workspace again to review the current certificate.".into());
    }
    install_ca(
        Path::new(&trust.certificate.trust_certificate),
        &trust.server_name,
    )
}

#[cfg(target_os = "macos")]
fn install_ca(certificate: &Path, server_name: &str) -> Result<(), String> {
    let output = std::process::Command::new("/usr/bin/security")
        .args(macos_trust_args(server_name, certificate))
        .stdin(std::process::Stdio::null())
        .output()
        .map_err(|e| format!("Could not request certificate trust: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "macOS did not approve certificate trust. {}",
            String::from_utf8_lossy(&output.stderr).trim()
        ));
    }
    Ok(())
}

#[cfg(target_os = "windows")]
fn install_ca(certificate: &Path, _server_name: &str) -> Result<(), String> {
    use std::os::windows::ffi::OsStrExt;
    use windows_sys::Win32::Security::Cryptography::{UI::*, *};
    let root: Vec<u16> = "ROOT\0".encode_utf16().collect();
    let file: Vec<u16> = certificate
        .as_os_str()
        .encode_wide()
        .chain(Some(0))
        .collect();
    let title: Vec<u16> = "Trust Hardcharger's local CA\0".encode_utf16().collect();
    unsafe {
        let store = CertOpenStore(
            CERT_STORE_PROV_SYSTEM_W,
            0,
            0,
            CERT_SYSTEM_STORE_CURRENT_USER,
            root.as_ptr().cast(),
        );
        if store.is_null() {
            return Err(format!(
                "Could not open your certificate store: {}",
                std::io::Error::last_os_error()
            ));
        }
        let source = CRYPTUI_WIZ_IMPORT_SRC_INFO {
            dwSize: std::mem::size_of::<CRYPTUI_WIZ_IMPORT_SRC_INFO>() as u32,
            dwSubjectChoice: CRYPTUI_WIZ_IMPORT_SUBJECT_FILE,
            Anonymous: CRYPTUI_WIZ_IMPORT_SRC_INFO_0 {
                pwszFileName: file.as_ptr(),
            },
            ..Default::default()
        };
        // Keep the OS confirmation wizard visible; import only to Current User Root.
        let imported = CryptUIWizImport(
            CRYPTUI_WIZ_IMPORT_NO_CHANGE_DEST_STORE | CRYPTUI_WIZ_IMPORT_ALLOW_CERT,
            std::ptr::null_mut(),
            title.as_ptr(),
            &source,
            store,
        );
        let failure = std::io::Error::last_os_error();
        CertCloseStore(store, 0);
        if imported == 0 {
            return Err(format!(
                "Certificate trust was cancelled or refused: {failure}"
            ));
        }
    }
    Ok(())
}

#[cfg(not(any(target_os = "macos", target_os = "windows")))]
fn install_ca(_certificate: &Path, _server_name: &str) -> Result<(), String> {
    Err("Use your Linux certificate manager to trust Hardcharger-local-CA.crt, then try opening the workspace again.".into())
}

fn host_name(name: &str) -> Result<String, String> {
    let settings = Settings {
        network: NetworkSettings {
            enabled: true,
            server_name: name.trim().into(),
            tls: false,
            password: "address-validation".into(),
            ..NetworkSettings::default()
        },
        ..Settings::default()
    };
    settings.validate()?;
    let name = name.trim().trim_matches(['[', ']']);
    let authority = if name.contains(':') {
        format!("[{name}]")
    } else {
        name.into()
    };
    let url = tauri::Url::parse(&format!("https://{authority}")).map_err(|e| e.to_string())?;
    Ok(url
        .host_str()
        .ok_or("Missing server address.")?
        .trim_matches(['[', ']'])
        .into())
}

pub fn generate(directory: &Path, server_name: &str) -> Result<GeneratedCertificate, String> {
    let mut names = vec![
        host_name(server_name)?,
        "localhost".into(),
        "127.0.0.1".into(),
        "::1".into(),
    ];
    let detected = info()?;
    if let Ok(host) = host_name(&detected.hostname) {
        names.push(host);
    }
    names.extend(detected.addresses.into_iter().map(|a| a.address));
    names.sort();
    names.dedup();
    let now = time::OffsetDateTime::now_utc();
    let expires = now + time::Duration::days(365);
    let mut ca_params = CertificateParams::default();
    ca_params.not_before = now - time::Duration::minutes(5);
    ca_params.not_after = expires;
    ca_params.is_ca = IsCa::Ca(BasicConstraints::Constrained(0));
    ca_params.key_usages = vec![KeyUsagePurpose::KeyCertSign, KeyUsagePurpose::CrlSign];
    ca_params.distinguished_name.push(
        DnType::CommonName,
        format!("Hardcharger ({server_name}) local CA"),
    );
    let ca_key = KeyPair::generate().map_err(|e| e.to_string())?;
    let ca = ca_params.self_signed(&ca_key).map_err(|e| e.to_string())?;
    let issuer = Issuer::from_params(&ca_params, &ca_key);
    let key = KeyPair::generate().map_err(|e| e.to_string())?;
    let mut params = CertificateParams::new(names.clone()).map_err(|e| e.to_string())?;
    params.not_before = now - time::Duration::minutes(5);
    params.not_after = expires;
    params.key_usages = vec![KeyUsagePurpose::DigitalSignature];
    params.extended_key_usages = vec![ExtendedKeyUsagePurpose::ServerAuth];
    params
        .distinguished_name
        .push(DnType::CommonName, server_name);
    let certificate = params.signed_by(&key, &issuer).map_err(|e| e.to_string())?;
    let folder = directory.join("certificates").join(random_secret()?);
    fs::create_dir_all(&folder).map_err(|e| e.to_string())?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(&folder, fs::Permissions::from_mode(0o700))
            .map_err(|e| e.to_string())?;
    }
    let cert_path = folder.join("server.pem");
    let key_path = folder.join("server.key");
    let trust_path = folder.join("Hardcharger-local-CA.crt");
    private_write(&key_path, key.serialize_pem().as_bytes())?;
    private_write(
        &cert_path,
        format!("{}{}", certificate.pem(), ca.pem()).as_bytes(),
    )?;
    private_write(&trust_path, ca.pem().as_bytes())?;
    // The CA private key is deliberately not written to disk or returned to the UI.
    let result = GeneratedCertificate {
        certificate: cert_path.to_string_lossy().into(),
        private_key: key_path.to_string_lossy().into(),
        trust_certificate: trust_path.to_string_lossy().into(),
        fingerprint: Sha256::digest(ca.der())
            .iter()
            .map(|b| format!("{b:02X}"))
            .collect::<Vec<_>>()
            .join(":"),
        expires: expires.date().to_string(),
        names,
    };
    private_write(
        &folder.join("certificate-info.json"),
        &serde_json::to_vec_pretty(&result).map_err(|e| e.to_string())?,
    )?;
    Ok(result)
}

pub fn generated(directory: &Path, certificate: &str) -> Option<GeneratedCertificate> {
    let path = Path::new(certificate);
    let folder = path.parent()?;
    if path.file_name()? != "server.pem" || folder.parent()? != directory.join("certificates") {
        return None;
    }
    let record: GeneratedCertificate =
        serde_json::from_slice(&fs::read(folder.join("certificate-info.json")).ok()?).ok()?;
    if record.certificate != certificate
        || Path::new(&record.trust_certificate) != folder.join("Hardcharger-local-CA.crt")
    {
        return None;
    }
    Some(record)
}

pub fn certificate_folder(directory: &Path, certificate: &str) -> Result<PathBuf, String> {
    let record = generated(directory, certificate)
        .ok_or("Choose a certificate generated by this app first.")?;
    Ok(Path::new(&record.trust_certificate)
        .parent()
        .ok_or("Missing certificate folder.")?
        .into())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn trust_confirmation_is_bound_to_the_generated_ca_bytes_and_current_server() {
        let directory = std::env::temp_dir().join(format!(
            "hardcharger-trust-check-{}",
            random_secret().unwrap()
        ));
        let certificate = generate(&directory, "desktop.test").unwrap();
        assert!(verified_generated(&directory, &certificate.certificate).is_ok());
        let settings = Settings {
            network: NetworkSettings {
                enabled: true,
                server_name: "desktop.test".into(),
                tls_cert: certificate.certificate.clone(),
                tls_key: certificate.private_key.clone(),
                ..NetworkSettings::default()
            },
            ..Settings::default()
        };
        // These must fail BEFORE any OS import. Tests never change system trust.
        assert!(
            trust_workspace_ca(&directory, &settings, "stale-fingerprint", "desktop.test").is_err()
        );
        assert!(trust_workspace_ca(
            &directory,
            &settings,
            &certificate.fingerprint,
            "another.test"
        )
        .is_err());
        let ca = fs::read(&certificate.trust_certificate).unwrap();
        fs::write(
            &certificate.trust_certificate,
            [ca.clone(), ca.clone()].concat(),
        )
        .unwrap();
        assert!(verified_generated(&directory, &certificate.certificate).is_err());
        fs::write(&certificate.trust_certificate, &ca).unwrap();
        let metadata = Path::new(&certificate.certificate)
            .parent()
            .unwrap()
            .join("certificate-info.json");
        let mut changed = certificate.clone();
        changed.fingerprint = "modified-metadata".into();
        fs::write(&metadata, serde_json::to_vec(&changed).unwrap()).unwrap();
        assert!(verified_generated(&directory, &certificate.certificate).is_err());
        fs::write(&metadata, serde_json::to_vec(&certificate).unwrap()).unwrap();
        fs::write(&certificate.certificate, &ca).unwrap(); // not the generated leaf + CA chain
        assert!(verified_generated(&directory, &certificate.certificate).is_err());
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn a_generated_certificate_covers_only_the_names_it_lists() {
        let record = GeneratedCertificate {
            certificate: String::new(),
            private_key: String::new(),
            trust_certificate: String::new(),
            fingerprint: String::new(),
            expires: String::new(),
            names: vec![
                "192.168.4.21".into(),
                "fd3d:5511::1".into(),
                "My-Mac.local".into(),
            ],
        };
        assert!(covers(&record, "192.168.4.21"));
        assert!(covers(&record, " [FD3D:5511:0::1] "));
        assert!(covers(&record, "my-mac.local"));
        assert!(!covers(&record, "192.168.4.22"));
        assert!(!covers(&record, "fd3d:5511::2"));
        assert!(!covers(&record, "other.local"));
        assert!(!covers(&record, ""));
    }

    #[test]
    fn a_missing_server_address_is_named_with_this_computers_current_ones() {
        // 192.0.2.0/24 is TEST-NET-1: never assigned to a real interface.
        let message = missing_address("192.0.2.21".parse().unwrap());
        assert!(message.starts_with("192.0.2.21 is "), "{message}");
        assert!(message.contains("Settings > Network access"), "{message}");
        if let Some(listed) = info()
            .unwrap()
            .addresses
            .iter()
            .find(|a| !a.address.contains(':'))
        {
            assert!(
                message.contains(&format!("{} ({})", listed.address, listed.interface)),
                "{message}"
            );
        }
    }

    #[test]
    fn macos_import_is_user_scoped_ssl_only_and_does_not_allow_hostname_or_expiry_errors() {
        let path = Path::new("/synthetic/path with spaces/local CA.crt");
        let args = macos_trust_args("desktop.test", path);
        let expected: Vec<std::ffi::OsString> = [
            "add-trusted-cert",
            "-r",
            "trustRoot",
            "-p",
            "ssl",
            "-s",
            "desktop.test",
            path.to_str().unwrap(),
        ]
        .into_iter()
        .map(Into::into)
        .collect();
        assert_eq!(args, expected);
        assert!(!args.iter().any(|arg| arg == "-d" || arg == "-e"));
    }
}
